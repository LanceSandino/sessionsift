func optimizationRoute(store *storage.Store, w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Cache-Control", "no-store")
	switch {
	case r.Method == http.MethodGet && r.URL.Path == "/api/v1/optimization":
		overview, err := buildOptimizationOverview(r, store)
		if err != nil {
			apiError(w, err)
			return
		}
		writeJSON(w, http.StatusOK, overview)
	case r.Method == http.MethodGet && r.URL.Path == "/api/v1/optimization/report.json":
		overview, err := buildOptimizationOverview(r, store)
		if err != nil {
			apiError(w, err)
			return
		}
		_ = store.RecordAdoption(r.Context(), optimize.AdoptionReportsExported, time.Now())
		w.Header().Set("Content-Disposition", `attachment; filename="sessionsift-optimization-report.json"`)
		w.Header().Set("Cache-Control", "no-store")
		writeJSON(w, http.StatusOK, optimize.SafeExport(overview))
	case r.Method == http.MethodGet && r.URL.Path == "/api/v1/optimization/report.md":
		overview, err := buildOptimizationOverview(r, store)
		if err != nil {
			apiError(w, err)
			return
		}
		_ = store.RecordAdoption(r.Context(), optimize.AdoptionReportsExported, time.Now())
		w.Header().Set("Content-Type", "text/markdown; charset=utf-8")
		w.Header().Set("Content-Disposition", `attachment; filename="sessionsift-optimization-report.md"`)
		w.Header().Set("Cache-Control", "no-store")
		w.WriteHeader(http.StatusOK)
		_, _ = io.WriteString(w, optimize.Markdown(overview))
	case r.Method == http.MethodPost && r.URL.Path == "/api/v1/optimization/experiments":
		createExperiment(store, w, r)
	case r.Method == http.MethodPost && r.URL.Path == "/api/v1/optimization/experiments/update":
		updateExperiment(store, w, r)
	case r.Method == http.MethodPost && r.URL.Path == "/api/v1/optimization/recommendations":
		setRecommendation(store, w, r)
	case r.Method == http.MethodPost && r.URL.Path == "/api/v1/optimization/adoption":
		recordAdoption(store, w, r)
	default:
		writeJSON(w, http.StatusNotFound, map[string]string{"error": "not found"})
	}
}

func buildOptimizationOverview(r *http.Request, store *storage.Store) (optimize.Overview, error) {
	sessions, err := store.ListSessions(r.Context())
	if err != nil {
		return optimize.Overview{}, err
	}
	experiments, err := store.ListExperiments(r.Context())
	if err != nil {
		return optimize.Overview{}, err
	}
	decisions, err := store.ListRecommendationDecisions(r.Context())
	if err != nil {
		return optimize.Overview{}, err
	}
	now := time.Now().UTC()
	adoption, err := store.AdoptionSummary(r.Context(), now.AddDate(0, 0, -7), now)
	if err != nil {
		return optimize.Overview{}, err
	}
	return optimize.BuildOverview(sessions, analytics.Build(sessions), experiments, decisions, adoption, now), nil
}

type experimentInput struct {
	ID                string `json:"id,omitempty"`
	Title             string `json:"title"`
	Hypothesis        string `json:"hypothesis,omitempty"`
	RecommendationID  string `json:"recommendation_id,omitempty"`
	BaselineSessionID string `json:"baseline_session_id"`
	FollowupSessionID string `json:"followup_session_id,omitempty"`
}

func createExperiment(store *storage.Store, w http.ResponseWriter, r *http.Request) {
	var input experimentInput
	if err := decodeOptimizationInput(w, r, &input); err != nil {
		writeJSON(w, http.StatusBadRequest, map[string]string{"error": err.Error()})
		return
	}
	if input.ID != "" {
		writeJSON(w, http.StatusBadRequest, map[string]string{"error": "experiment id is generated by SessionSift"})
		return
	}
	if err := validateExperimentSessions(r, store, input.BaselineSessionID, input.FollowupSessionID); err != nil {
		writeJSON(w, http.StatusBadRequest, map[string]string{"error": err.Error()})
		return
	}
	now := time.Now().UTC()
	experiment := optimize.Experiment{ID: newOptimizationID(), Title: input.Title, Hypothesis: input.Hypothesis, RecommendationID: input.RecommendationID, BaselineSessionID: input.BaselineSessionID, FollowupSessionID: input.FollowupSessionID, Status: experimentStatus(input.FollowupSessionID), CreatedAt: now, UpdatedAt: now}
	if err := store.SaveExperiment(r.Context(), experiment); err != nil {
		writeJSON(w, http.StatusBadRequest, map[string]string{"error": err.Error()})
		return
	}
	_ = store.RecordAdoption(r.Context(), optimize.AdoptionExperimentsCreated, now)
	writeJSON(w, http.StatusCreated, experiment)
}

func updateExperiment(store *storage.Store, w http.ResponseWriter, r *http.Request) {
	var input experimentInput
	if err := decodeOptimizationInput(w, r, &input); err != nil {
		writeJSON(w, http.StatusBadRequest, map[string]string{"error": err.Error()})
		return
	}
	existing, err := store.ListExperiments(r.Context())
	if err != nil {
		apiError(w, err)
		return
	}
	var created time.Time
	for _, item := range existing {
		if item.ID == input.ID {
			created = item.CreatedAt
			break
		}
	}
	if created.IsZero() {
		writeJSON(w, http.StatusNotFound, map[string]string{"error": "experiment not found"})
		return
	}
	if err := validateExperimentSessions(r, store, input.BaselineSessionID, input.FollowupSessionID); err != nil {
		writeJSON(w, http.StatusBadRequest, map[string]string{"error": err.Error()})
		return
	}
	experiment := optimize.Experiment{ID: input.ID, Title: input.Title, Hypothesis: input.Hypothesis, RecommendationID: input.RecommendationID, BaselineSessionID: input.BaselineSessionID, FollowupSessionID: input.FollowupSessionID, Status: experimentStatus(input.FollowupSessionID), CreatedAt: created, UpdatedAt: time.Now().UTC()}
	if err := store.SaveExperiment(r.Context(), experiment); err != nil {
		writeJSON(w, http.StatusBadRequest, map[string]string{"error": err.Error()})
		return
	}
	writeJSON(w, http.StatusOK, experiment)
}

func validateExperimentSessions(r *http.Request, store *storage.Store, baseline, followup string) error {
	if baseline == "" {
		return errors.New("a baseline session is required")
	}
	if baseline == followup {
		return errors.New("baseline and follow-up sessions must differ")
	}
	if _, err := store.GetSession(r.Context(), baseline); err != nil {
		return errors.New("baseline session was not found")
	}
	if followup != "" {
		if _, err := store.GetSession(r.Context(), followup); err != nil {
			return errors.New("follow-up session was not found")
		}
	}
	return nil
}

func experimentStatus(followup string) optimize.ExperimentStatus {
	if followup != "" {
		return optimize.ExperimentMeasured
	}
	return optimize.ExperimentRunning
}

func setRecommendation(store *storage.Store, w http.ResponseWriter, r *http.Request) {
	var input struct {
		RecommendationID string                       `json:"recommendation_id"`
		State            optimize.RecommendationState `json:"state"`
	}
	if err := decodeOptimizationInput(w, r, &input); err != nil {
		writeJSON(w, http.StatusBadRequest, map[string]string{"error": err.Error()})
		return
	}
	decision := optimize.RecommendationDecision{RecommendationID: input.RecommendationID, State: input.State, UpdatedAt: time.Now().UTC()}
	if err := store.SetRecommendationDecision(r.Context(), decision); err != nil {
		writeJSON(w, http.StatusBadRequest, map[string]string{"error": err.Error()})
		return
	}
	_ = store.RecordAdoption(r.Context(), optimize.AdoptionRecommendationsChanged, decision.UpdatedAt)
	writeJSON(w, http.StatusOK, decision)
}

func recordAdoption(store *storage.Store, w http.ResponseWriter, r *http.Request) {
	var input struct {
		Event optimize.AdoptionEvent `json:"event"`
	}
	if err := decodeOptimizationInput(w, r, &input); err != nil {
		writeJSON(w, http.StatusBadRequest, map[string]string{"error": err.Error()})
		return
	}
	if err := store.RecordAdoption(r.Context(), input.Event, time.Now()); err != nil {
		writeJSON(w, http.StatusBadRequest, map[string]string{"error": err.Error()})
		return
	}
	writeJSON(w, http.StatusOK, map[string]bool{"recorded": true})
}

func decodeOptimizationInput(w http.ResponseWriter, r *http.Request, target any) error {
	decoder := json.NewDecoder(http.MaxBytesReader(w, r.Body, 8<<10))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(target); err != nil {
		return errors.New("invalid optimization request")
	}
	if err := decoder.Decode(&struct{}{}); err != io.EOF {
		return errors.New("invalid optimization request")
	}
	return nil
}

func newOptimizationID() string {
	var value [12]byte
	if _, err := rand.Read(value[:]); err != nil {
		return "exp_" + strings.ReplaceAll(time.Now().UTC().Format("20060102150405.000000000"), ".", "")
	}
	return "exp_" + hex.EncodeToString(value[:])
}
