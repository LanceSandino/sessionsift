#!/usr/bin/env python3
"""Generate the LanceSandino/homebrew-tap formula from verified SessionSift release archives."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import stat
import sys
import tarfile

TARGETS = (("darwin", "amd64"), ("linux", "amd64"))
ORIGIN = "https://github.com/LanceSandino/sessionsift"
PAYLOAD = ("sessionsift", "LICENSE", "NOTICE", "README.md", "SECURITY.md", "CHANGELOG.md", "VERSION")
SEMVER = re.compile(r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?\Z", re.ASCII)


def regular(path):
    if not stat.S_ISREG(path.lstat().st_mode):
        raise ValueError(f"expected regular file: {path.name}")


def sha256(path):
    digest = hashlib.sha256()
    with path.open("rb") as file:
        for chunk in iter(lambda: file.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def release_inputs(version_file, dist):
    regular(version_file)
    version = version_file.read_text().strip()
    if not SEMVER.fullmatch(version):
        raise ValueError("VERSION must contain one SemVer version")
    expected = {f"sessionsift_{version}_{os_name}_{arch}.tar.gz": f"{os_name}/{arch}" for os_name, arch in TARGETS}
    sums = dist / "SHA256SUMS"
    regular(sums)
    checksums = {}
    for line in sums.read_text().splitlines():
        match = re.fullmatch(r"([0-9a-f]{64})  (\S+)", line)
        if not match:
            raise ValueError("invalid SHA256SUMS entry")
        digest, name = match.groups()
        if name in checksums:
            raise ValueError("duplicate SHA256SUMS entry")
        checksums[name] = digest
    if not set(expected) <= set(checksums):
        raise ValueError("SHA256SUMS must list both supported target archives")
    for name, target in expected.items():
        path = dist / name
        regular(path)
        if sha256(path) != checksums[name]:
            raise ValueError(f"checksum mismatch: {name}")
        prefix = name[: -len(".tar.gz")] + "/"
        with tarfile.open(path, "r:gz") as archive:
            member = archive.getmember(prefix + "BUILD-METADATA.json")
            if not member.isfile() or member.size > 65536:
                raise ValueError("invalid archive metadata")
            metadata = json.load(archive.extractfile(member))
            if metadata.get("version") != version or metadata.get("target") != target:
                raise ValueError("archive metadata does not match VERSION and target")
            for required in PAYLOAD:
                if not archive.getmember(prefix + required).isfile():
                    raise ValueError(f"missing archive payload: {required}")
    return version, {name: checksums[name] for name in expected}


def formula(version, checksums):
    def target(os_name, arch):
        name = f"sessionsift_{version}_{os_name}_{arch}.tar.gz"
        return (f'      url "{ORIGIN}/releases/download/v{version}/{name}"\n'
                f'      sha256 "{checksums[name]}"')
    return f'''# Generated by scripts/homebrew.py from verified release archives.
class Sessionsift < Formula
  desc "Local, read-only analysis of AI coding sessions"
  homepage "{ORIGIN}"
  license "PolyForm-Noncommercial-1.0.0"

  depends_on arch: :x86_64

  on_macos do
    on_intel do
{target("darwin", "amd64")}
    end
  end

  on_linux do
    on_intel do
{target("linux", "amd64")}
    end
  end

  version "{version}" if version.to_s != "{version}"

  def install
    bin.install "sessionsift"
    doc.install "NOTICE", "README.md", "SECURITY.md", "CHANGELOG.md"
    pkgshare.install "LICENSE"
  end

  service do
    run [opt_bin/"sessionsift", "start"]
    keep_alive true
    require_root false
    environment_variables HOME: Dir.home
    working_dir Dir.home
  end

  test do
    home = testpath/"isolated-home"
    home.mkpath
    ENV["HOME"] = home.to_s
    ENV["SESSIONSIFT_HOME"] = (home/"state").to_s
    ENV["CODEX_HOME"] = (home/"codex").to_s
    ENV["CLAUDE_HOME"] = (home/"claude").to_s
    ENV["CLAUDE_CONFIG_DIR"] = (home/"claude").to_s
    assert_equal version.to_s, shell_output("#{{bin}}/sessionsift version").strip
    assert_match "SessionSift", shell_output("#{{bin}}/sessionsift doctor")
    assert_match "sessionsift", shell_output("#{{bin}}/sessionsift setup mcp")
    assert_path_exists doc/"NOTICE"
    assert_path_exists pkgshare/"LICENSE"
  end
end
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version-file", type=Path, default=Path("VERSION"))
    parser.add_argument("--dist-dir", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        version, checksums = release_inputs(args.version_file, args.dist_dir)
        if args.output.is_symlink():
            raise ValueError("formula output must not be a symlink")
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(formula(version, checksums))
    except (OSError, ValueError, KeyError, tarfile.TarError) as error:
        print(f"Homebrew generation failed: {error}", file=sys.stderr)
        return 1
    print(f"Generated {args.output.name} for {version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
